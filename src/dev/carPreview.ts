// Dev-only car turntable: /dev/car.html?yaw=0.6&pitch=0.2&dist=6&hour=16
import * as THREE from 'three';
import '@fontsource/chakra-petch/700.css';
import { Environment } from '../render/environment';
import { carDef, carPhysics } from '../data';
import { Vehicle } from '../physics/vehicle';
import { FlatWorld } from '../physics/collision';
import { CarView } from '../vehicles/carView';
import { emptyInput } from '../physics/types';

const q = new URLSearchParams(location.search);
const renderer = new THREE.WebGLRenderer({ antialias: true });
renderer.setSize(innerWidth, innerHeight);
renderer.setPixelRatio(Math.min(2, devicePixelRatio));
renderer.toneMapping = THREE.ACESFilmicToneMapping;
renderer.shadowMap.enabled = true;
renderer.shadowMap.type = THREE.PCFSoftShadowMap;
document.body.appendChild(renderer.domElement);
const scene = new THREE.Scene();
const env = new Environment(scene, renderer);
env.setShadowQuality(2);
env.setHour(Number(q.get('hour') ?? 16));
const ground = new THREE.Mesh(new THREE.CircleGeometry(60, 64), new THREE.MeshStandardMaterial({ color: 0x55565a, roughness: 0.9 }));
ground.rotation.x = -Math.PI / 2;
ground.receiveShadow = true;
scene.add(ground);
const world = new FlatWorld();
const v = new Vehicle(carPhysics('sakura_s15'));
v.reset(world, 0, 0, 0);
const inp = emptyInput();
inp.steer = Number(q.get('steer') ?? 0);
for (let i = 0; i < 240; i++) v.step(1 / 120, inp, world);
const view = new CarView(v, carDef('sakura_s15'), q.get('paint') ?? '#c8102e');
scene.add(view.group);
view.update(1, 0);
view.setHeadlights(q.get('lights') === '1');
const cam = new THREE.PerspectiveCamera(Number(q.get('fov') ?? 40), innerWidth / innerHeight, 0.05, 5000);
const yaw = Number(q.get('yaw') ?? 0.7), pitch = Number(q.get('pitch') ?? 0.18), dist = Number(q.get('dist') ?? 7.5);
cam.position.set(Math.sin(yaw) * Math.cos(pitch) * dist, 0.35 + Math.sin(pitch) * dist, Math.cos(yaw) * Math.cos(pitch) * dist);
cam.lookAt(0, 0.35, 0);
env.follow(new THREE.Vector3());
renderer.render(scene, cam);
(window as any).__ready = true;
